--TOP 5 VEHICLES BY SERVICE COST--
SELECT
    VEHICLE_ID,
    REGISTRATION_NUMBER,
    MAKE,
    MODEL,
    CUSTOMER_NAME,
    TOTAL_SERVICE_COST
FROM SERVICE_ANALYTICS
ORDER BY TOTAL_SERVICE_COST DESC
LIMIT 5;

--SERVICE COST BY SERVICE TYPE--
SELECT
    SERVICE_TYPE,
    COUNT(*) AS TOTAL_SERVICES,
    SUM(TOTAL_SERVICE_COST) AS TOTAL_COST,
    AVG(TOTAL_SERVICE_COST) AS AVERAGE_COST
FROM SERVICE_ANALYTICS
GROUP BY SERVICE_TYPE
ORDER BY TOTAL_COST DESC;

--PARTS USAGE--
SELECT
    PART_ID,
    PART_NAME,
    CATEGORY,
    SUPPLIER_NAME,
    SUM(QUANTITY) AS TOTAL_QUANTITY_USED,
    SUM(UNIT_COST * QUANTITY) AS TOTAL_PART_COST
FROM SERVICE_ANALYTICS
WHERE PART_ID IS NOT NULL
GROUP BY
    PART_ID,
    PART_NAME,
    CATEGORY,
    SUPPLIER_NAME
ORDER BY TOTAL_QUANTITY_USED DESC;

