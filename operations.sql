--creating a view for better analysis--
CREATE OR REPLACE VIEW SERVICE_ANALYTICS AS
SELECT
    sh.SERVICE_ID,
    sh.SERVICE_DATE,
    sh.SERVICE_TYPE,
    sh.SERVICE_STATUS,

    c.CUSTOMER_ID,
    c.CUSTOMER_NAME,
    c.CITY,

    v.VEHICLE_ID,
    v.REGISTRATION_NUMBER,
    v.MAKE,
    v.MODEL,
    v.MANUFACTURING_YEAR,
    v.VEHICLE_TYPE,

    sh.PART_ID,
    p.PART_NAME,
    p.CATEGORY,
    p.SUPPLIER_NAME,

    COALESCE(sh.QUANTITY, 0) AS QUANTITY,
    COALESCE(p.UNIT_COST, 0) AS UNIT_COST,
    COALESCE(sh.LABOR_COST, 0) AS LABOR_COST,

    (COALESCE(p.UNIT_COST, 0) * COALESCE(sh.QUANTITY, 0))
        + COALESCE(sh.LABOR_COST, 0) AS TOTAL_SERVICE_COST

FROM SERVICE_HISTORY sh

JOIN VEHICLES v
    ON sh.VEHICLE_ID = v.VEHICLE_ID

JOIN CUSTOMERS c
    ON v.CUSTOMER_ID = c.CUSTOMER_ID

LEFT JOIN PARTS p
    ON sh.PART_ID = p.PART_ID;

--verifying view--
SELECT *
FROM SERVICE_ANALYTICS
LIMIT 100;

--mini dashboard query--
SELECT
    COUNT(DISTINCT CUSTOMER_ID) AS TOTAL_CUSTOMERS,
    COUNT(DISTINCT VEHICLE_ID) AS TOTAL_VEHICLES,
    COUNT(DISTINCT SERVICE_ID) AS TOTAL_SERVICES,
    SUM(TOTAL_SERVICE_COST) AS TOTAL_SERVICE_COST,
    AVG(TOTAL_SERVICE_COST) AS AVERAGE_SERVICE_COST
FROM SERVICE_ANALYTICS;