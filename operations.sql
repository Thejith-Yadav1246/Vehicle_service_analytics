--relationship checklist--
SELECT
    v.VEHICLE_ID,
    v.REGISTRATION_NUMBER,
    c.CUSTOMER_NAME,
    sh.SERVICE_ID,
    p.PART_NAME,
    sh.QUANTITY,
    sh.LABOR_COST,
    sh.SERVICE_STATUS
FROM VEHICLES v
JOIN CUSTOMERS c
    ON v.CUSTOMER_ID = c.CUSTOMER_ID
JOIN SERVICE_HISTORY sh
    ON v.VEHICLE_ID = sh.VEHICLE_ID
LEFT JOIN PARTS p
    ON sh.PART_ID = p.PART_ID
ORDER BY v.VEHICLE_ID, sh.SERVICE_DATE;

--Calculating Total Service Cost--
SELECT
    sh.SERVICE_ID,
    sh.VEHICLE_ID,
    sh.SERVICE_DATE,
    sh.SERVICE_TYPE,
    p.PART_NAME,
    COALESCE(sh.QUANTITY, 0) AS QUANTITY,
    COALESCE(p.UNIT_COST, 0) AS UNIT_COST,
    sh.LABOR_COST,
    (COALESCE(p.UNIT_COST, 0) * COALESCE(sh.QUANTITY, 0))
        + COALESCE(sh.LABOR_COST, 0) AS TOTAL_SERVICE_COST,
    sh.SERVICE_STATUS
FROM SERVICE_HISTORY sh
LEFT JOIN PARTS p
    ON sh.PART_ID = p.PART_ID
ORDER BY sh.SERVICE_DATE;

--Customer Service Summary--
SELECT
    c.CUSTOMER_ID,
    c.CUSTOMER_NAME,
    COUNT(sh.SERVICE_ID) AS TOTAL_SERVICES,
    SUM(
        (COALESCE(p.UNIT_COST, 0) * COALESCE(sh.QUANTITY, 0))
        + COALESCE(sh.LABOR_COST, 0)
    ) AS TOTAL_SERVICE_COST
FROM CUSTOMERS c
JOIN VEHICLES v
    ON c.CUSTOMER_ID = v.CUSTOMER_ID
JOIN SERVICE_HISTORY sh
    ON v.VEHICLE_ID = sh.VEHICLE_ID
LEFT JOIN PARTS p
    ON sh.PART_ID = p.PART_ID
GROUP BY
    c.CUSTOMER_ID,
    c.CUSTOMER_NAME
ORDER BY TOTAL_SERVICE_COST DESC;

--vehicle-level maintenance analysis---
SELECT
    v.VEHICLE_ID,
    v.REGISTRATION_NUMBER,
    v.MAKE,
    v.MODEL,
    c.CUSTOMER_NAME,
    COUNT(sh.SERVICE_ID) AS TOTAL_SERVICES,
    SUM(
        (COALESCE(p.UNIT_COST, 0) * COALESCE(sh.QUANTITY, 0))
        + COALESCE(sh.LABOR_COST, 0)
    ) AS TOTAL_SERVICE_COST
FROM VEHICLES v
JOIN CUSTOMERS c
    ON v.CUSTOMER_ID = c.CUSTOMER_ID
JOIN SERVICE_HISTORY sh
    ON v.VEHICLE_ID = sh.VEHICLE_ID
LEFT JOIN PARTS p
    ON sh.PART_ID = p.PART_ID
GROUP BY
    v.VEHICLE_ID,
    v.REGISTRATION_NUMBER,
    v.MAKE,
    v.MODEL,
    c.CUSTOMER_NAME
ORDER BY TOTAL_SERVICE_COST DESC;

--most used part--
SELECT
    p.PART_ID,
    p.PART_NAME,
    p.CATEGORY,
    p.SUPPLIER_NAME,
    SUM(sh.QUANTITY) AS TOTAL_QUANTITY_USED,
    COUNT(sh.SERVICE_ID) AS SERVICES_USING_PART,
    SUM(p.UNIT_COST * sh.QUANTITY) AS TOTAL_PART_COST
FROM PARTS p
JOIN SERVICE_HISTORY sh
    ON p.PART_ID = sh.PART_ID
GROUP BY
    p.PART_ID,
    p.PART_NAME,
    p.CATEGORY,
    p.SUPPLIER_NAME
ORDER BY TOTAL_QUANTITY_USED DESC;

--Supplier Cost Analysis--
SELECT
    p.SUPPLIER_NAME,
    COUNT(DISTINCT p.PART_ID) AS NUMBER_OF_PARTS,
    SUM(sh.QUANTITY) AS TOTAL_QUANTITY_SUPPLIED,
    SUM(p.UNIT_COST * sh.QUANTITY) AS TOTAL_PART_COST
FROM PARTS p
JOIN SERVICE_HISTORY sh
    ON p.PART_ID = sh.PART_ID
GROUP BY p.SUPPLIER_NAME
ORDER BY TOTAL_PART_COST DESC;

--Service Status Analysis--
SELECT
    SERVICE_STATUS,
    COUNT(*) AS TOTAL_SERVICES,
    SUM(
        (COALESCE(p.UNIT_COST, 0) * COALESCE(sh.QUANTITY, 0))
        + COALESCE(sh.LABOR_COST, 0)
    ) AS TOTAL_SERVICE_COST,
    AVG(
        (COALESCE(p.UNIT_COST, 0) * COALESCE(sh.QUANTITY, 0))
        + COALESCE(sh.LABOR_COST, 0)
    ) AS AVERAGE_SERVICE_COST
FROM SERVICE_HISTORY sh
LEFT JOIN PARTS p
    ON sh.PART_ID = p.PART_ID
GROUP BY SERVICE_STATUS
ORDER BY TOTAL_SERVICES DESC;

--Service-Type Analysis--
SELECT
    sh.SERVICE_TYPE,
    COUNT(*) AS TOTAL_SERVICES,
    SUM(
        (COALESCE(p.UNIT_COST, 0) * COALESCE(sh.QUANTITY, 0))
        + COALESCE(sh.LABOR_COST, 0)
    ) AS TOTAL_SERVICE_COST,
    AVG(
        (COALESCE(p.UNIT_COST, 0) * COALESCE(sh.QUANTITY, 0))
        + COALESCE(sh.LABOR_COST, 0)
    ) AS AVERAGE_SERVICE_COST
FROM SERVICE_HISTORY sh
LEFT JOIN PARTS p
    ON sh.PART_ID = p.PART_ID
GROUP BY sh.SERVICE_TYPE
ORDER BY TOTAL_SERVICES DESC;

