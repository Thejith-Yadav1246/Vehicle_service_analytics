--Monthly Service Trend--
SELECT
    DATE_TRUNC('MONTH', SERVICE_DATE) AS SERVICE_MONTH,
    COUNT(*) AS TOTAL_SERVICES,
    SUM(TOTAL_SERVICE_COST) AS TOTAL_SERVICE_COST,
    AVG(TOTAL_SERVICE_COST) AS AVERAGE_SERVICE_COST
FROM SERVICE_ANALYTICS
GROUP BY DATE_TRUNC('MONTH', SERVICE_DATE)
ORDER BY SERVICE_MONTH;

--CUSTOMER LIFETIME SERVICE VALUE--
SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    COUNT(DISTINCT VEHICLE_ID) AS VEHICLES_OWNED,
    COUNT(DISTINCT SERVICE_ID) AS TOTAL_SERVICES,
    SUM(TOTAL_SERVICE_COST) AS TOTAL_SERVICE_COST,
    ROUND(AVG(TOTAL_SERVICE_COST), 2) AS AVG_SERVICE_COST
FROM SERVICE_ANALYTICS
GROUP BY
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY
ORDER BY TOTAL_SERVICE_COST DESC;